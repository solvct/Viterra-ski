#!/usr/bin/env python3
"""Package the current Viterra website for static hosting."""
from pathlib import Path
from urllib.parse import urlparse
from xml.sax.saxutils import escape
import argparse
import json
import re
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--origin", help="Public origin, e.g. https://example.com")
    args = parser.parse_args()
    origin = args.origin.rstrip("/") if args.origin else None
    if origin and (urlparse(origin).scheme != "https" or not urlparse(origin).netloc):
        parser.error("--origin must be a complete HTTPS origin")

    manifest = json.loads((ROOT / "reference-manifest.json").read_text())
    output = ROOT / "dist"
    marker = output / ".viterra-static-build"
    if output.exists() and any(output.iterdir()) and not marker.exists():
        raise RuntimeError("dist already contains files from another build; refusing to replace it")
    if marker.exists():
        shutil.rmtree(output)
    output.mkdir(exist_ok=True)
    marker.write_text("Generated by scripts/build_static.py\n")

    for route in manifest["routes"]:
        relative = Path(route.strip("/")) / "index.html"
        page = (ROOT / relative).read_text()
        if origin:
            canonical = origin + (route if route != "/" else "/")
            page = re.sub(r'<link\b[^>]*rel="canonical"[^>]*>', "", page)
            page = re.sub(r'<meta\b[^>]*property="og:url"[^>]*>', "", page)
            page = page.replace("</head>", f'<link rel="canonical" href="{escape(canonical)}">\n<meta property="og:url" content="{escape(canonical)}">\n</head>')
        destination = output / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(page)

    shutil.copytree(ROOT / "reference-runtime", output / "reference-runtime")
    for name in ("site-overrides.css", "site-overrides.js", "favicon.svg", "apple-touch-icon.png"):
        shutil.copy2(ROOT / name, output / name)
    shutil.copy2(output / "404" / "index.html", output / "404.html")

    if origin:
        urls = "\n".join(f"  <url><loc>{escape(origin + route)}</loc></url>"
                         for route in manifest["routes"] if route not in ("/404", "/test"))
        (output / "sitemap.xml").write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + "\n</urlset>\n")
        (output / "robots.txt").write_text(f"User-agent: *\nAllow: /\nDisallow: /test\nSitemap: {origin}/sitemap.xml\n")

    release = ROOT / "release"
    release.mkdir(exist_ok=True)
    archive = release / "viterra-site.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
        files = sorted(path for path in output.rglob("*") if path.is_file() and path != marker)
        for path in files:
            bundle.write(path, path.relative_to(output))
    print(f"Prepared {len(files)} public files in {output}")
    print(f"Upload archive: {archive}")


if __name__ == "__main__":
    main()
